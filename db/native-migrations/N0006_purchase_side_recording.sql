-- P0-04B ERP increment ERP-A (EA v2.2 EA-R03; Shared erp/v2 catalogue version 2,
-- ADR-SHARED-037; ADR-ERP-022 amendment): purchase-side and vendor-payment
-- RECORDING classes at the database COMMIT boundary, for placed AD_Clients only.
--
-- 1. Classification by the stored row. A governed source document's class is
--    decided from its own committed-or-current row, never a caller value:
--      C_Order          IsSOTrx=Y -> erp.sales-order.complete
--                       IsSOTrx=N -> erp.purchase-order.complete
--      M_InOut          IsSOTrx=Y -> erp.shipment.complete
--                       IsSOTrx=N and MovementType='V+' (vendor receipt)
--                                 -> erp.material-receipt.complete
--      C_Invoice        IsSOTrx=Y -> erp.customer-invoice.issue
--                       IsSOTrx=N and base type API (AP invoice)
--                                 -> erp.vendor-invoice.record
--      C_Payment        IsReceipt=Y -> erp.payment.record
--                       IsReceipt=N, not online, not created from a payment
--                       selection -> erp.vendor-payment.record
--      C_AllocationHdr  every line a sales invoice/receipt -> erp.allocation.record
--                       every line an AP invoice/recordable vendor payment
--                                 -> erp.payables-allocation.record
--    Anything else has no class and stays denied: vendor returns (V-), AP credit
--    memos, mixed AP/AR allocations (no netting), empty allocations, online
--    outbound payments and payments generated by a payment selection.
-- 2. Recording is never disbursement (ADR-SHARED-035). Native payment selection
--    rows, which iDempiere uses to print/export remittances and bank files,
--    are refused outright for a placed client.
-- 3. Matching rows (M_MatchPO, M_MatchInv) are never operations of their own:
--    each is a consequence of exactly one deterministic root document and is
--    fenced, and its ledger posting attributed, through that root:
--      M_MatchPO  with a receipt line -> its material receipt; otherwise
--                 with an invoice line -> its vendor invoice
--      M_MatchInv -> its vendor invoice
--
-- Ids are NUMERIC(10) in iDempiere: every call site casts (N0004).

-- The catalogued class of a stored source document, or NULL.
CREATE FUNCTION baobab_native.governed_class_of(p_table text, p_record integer)
RETURNS text LANGUAGE plpgsql STABLE AS $$
DECLARE result text; sales integer; payables integer; other integer;
BEGIN
  CASE lower(p_table)
    WHEN 'gl_journal' THEN
      SELECT 'erp.gl-journal.post' INTO result FROM adempiere.gl_journal WHERE gl_journal_id = p_record;
    WHEN 'c_order' THEN
      SELECT CASE issotrx WHEN 'Y' THEN 'erp.sales-order.complete' WHEN 'N' THEN 'erp.purchase-order.complete' END
        INTO result FROM adempiere.c_order WHERE c_order_id = p_record;
    WHEN 'm_inout' THEN
      SELECT CASE WHEN issotrx = 'Y' THEN 'erp.shipment.complete'
                  WHEN issotrx = 'N' AND movementtype = 'V+' THEN 'erp.material-receipt.complete' END
        INTO result FROM adempiere.m_inout WHERE m_inout_id = p_record;
    WHEN 'c_invoice' THEN
      SELECT CASE WHEN i.issotrx = 'Y' THEN 'erp.customer-invoice.issue'
                  WHEN i.issotrx = 'N' AND dt.docbasetype = 'API' THEN 'erp.vendor-invoice.record' END
        INTO result
        FROM adempiere.c_invoice i
        LEFT JOIN adempiere.c_doctype dt
          ON dt.c_doctype_id = COALESCE(NULLIF(i.c_doctype_id, 0), i.c_doctypetarget_id)
       WHERE i.c_invoice_id = p_record;
    WHEN 'c_payment' THEN
      SELECT CASE WHEN p.isreceipt = 'Y' THEN 'erp.payment.record'
                  WHEN p.isreceipt = 'N' AND p.isonline = 'N'
                       AND NOT EXISTS (SELECT 1 FROM adempiere.c_payselectioncheck c
                                        WHERE c.c_payment_id = p.c_payment_id)
                  THEN 'erp.vendor-payment.record' END
        INTO result FROM adempiere.c_payment p WHERE p.c_payment_id = p_record;
    WHEN 'c_allocationhdr' THEN
      SELECT count(*) FILTER (WHERE baobab_native.allocation_line_side(al.c_invoice_id::integer,
                                      al.c_payment_id::integer) = 'SALES'),
             count(*) FILTER (WHERE baobab_native.allocation_line_side(al.c_invoice_id::integer,
                                      al.c_payment_id::integer) = 'PAYABLES'),
             count(*) FILTER (WHERE baobab_native.allocation_line_side(al.c_invoice_id::integer,
                                      al.c_payment_id::integer) IS NULL)
        INTO sales, payables, other
        FROM adempiere.c_allocationline al WHERE al.c_allocationhdr_id = p_record;
      result := CASE WHEN other = 0 AND sales > 0 AND payables = 0 THEN 'erp.allocation.record'
                     WHEN other = 0 AND payables > 0 AND sales = 0 THEN 'erp.payables-allocation.record' END;
    ELSE
      result := NULL;
  END CASE;
  RETURN result;
END $$;

-- The side of one allocation line: SALES when every document it joins is a
-- sales invoice or a receipt, PAYABLES when every document it joins is an AP
-- invoice or a recordable vendor payment, NULL otherwise (mixed or ungoverned).
CREATE FUNCTION baobab_native.allocation_line_side(p_invoice integer, p_payment integer)
RETURNS text LANGUAGE sql STABLE AS $$
  WITH sides AS (
    SELECT CASE baobab_native.governed_class_of('C_Invoice', p_invoice)
             WHEN 'erp.customer-invoice.issue' THEN 'SALES'
             WHEN 'erp.vendor-invoice.record' THEN 'PAYABLES' ELSE 'NONE' END AS side
     WHERE COALESCE(p_invoice, 0) > 0
    UNION ALL
    SELECT CASE baobab_native.governed_class_of('C_Payment', p_payment)
             WHEN 'erp.payment.record' THEN 'SALES'
             WHEN 'erp.vendor-payment.record' THEN 'PAYABLES' ELSE 'NONE' END
     WHERE COALESCE(p_payment, 0) > 0)
  SELECT CASE WHEN count(*) = 0 OR bool_or(side = 'NONE') THEN NULL
              WHEN bool_and(side = 'SALES') THEN 'SALES'
              WHEN bool_and(side = 'PAYABLES') THEN 'PAYABLES' END
    FROM sides
$$;

-- The governed root a ledger or matching row belongs to: a governed source
-- document is its own root; a matching row has exactly one deterministic root.
CREATE FUNCTION baobab_native.governed_root(p_table text, p_record integer,
                                            OUT root_table text, OUT root_record integer)
LANGUAGE plpgsql STABLE AS $$
BEGIN
  CASE lower(p_table)
    WHEN 'm_matchpo' THEN
      SELECT CASE WHEN COALESCE(mp.m_inoutline_id, 0) > 0 THEN 'M_InOut'
                  WHEN COALESCE(mp.c_invoiceline_id, 0) > 0 THEN 'C_Invoice' END,
             CASE WHEN COALESCE(mp.m_inoutline_id, 0) > 0 THEN iol.m_inout_id::integer
                  WHEN COALESCE(mp.c_invoiceline_id, 0) > 0 THEN il.c_invoice_id::integer END
        INTO root_table, root_record
        FROM adempiere.m_matchpo mp
        LEFT JOIN adempiere.m_inoutline iol ON iol.m_inoutline_id = mp.m_inoutline_id
        LEFT JOIN adempiere.c_invoiceline il ON il.c_invoiceline_id = mp.c_invoiceline_id
       WHERE mp.m_matchpo_id = p_record;
    WHEN 'm_matchinv' THEN
      SELECT 'C_Invoice', il.c_invoice_id::integer INTO root_table, root_record
        FROM adempiere.m_matchinv mi JOIN adempiere.c_invoiceline il ON il.c_invoiceline_id = mi.c_invoiceline_id
       WHERE mi.m_matchinv_id = p_record;
    ELSE
      root_table := p_table;
      root_record := p_record;
  END CASE;
END $$;

-- The same check for an explicit class; the JVM uses it to reuse a decision
-- in the same transaction only for exactly the same class.
CREATE FUNCTION baobab_native.has_current_attribution_for(p_client integer, p_table text, p_record integer,
                                                          p_class text)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT p_class IS NOT NULL AND EXISTS (
    SELECT 1 FROM baobab_native.finance_authority_attribution a
     WHERE a.txid = txid_current() AND a.ad_client_id = p_client
       AND a.decision_id IS NOT NULL
       AND lower(a.source_table) = lower(p_table) AND a.source_record_id = p_record
       AND a.operation_class = p_class
       AND a.authority_expires_at > clock_timestamp())
$$;

-- True when THIS transaction holds a still-current attribution of the source
-- document's OWN class, as decided from its stored row now (redefines N0005).
CREATE OR REPLACE FUNCTION baobab_native.has_governed_attribution(p_client integer, p_table text, p_record integer)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT baobab_native.has_current_attribution_for(p_client, p_table, p_record,
                                                   baobab_native.governed_class_of(p_table, p_record))
$$;

-- N0005's table-only helpers are superseded by governed_class_of; keep them
-- consistent so nothing can call a stale, purchase-blind definition.
CREATE OR REPLACE FUNCTION baobab_native.direction_holds(p_table text, p_record integer)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT baobab_native.governed_class_of(p_table, p_record) IS NOT NULL
$$;

-- Ledger rows: the source (or a matching row's root) must hold current
-- authority of its own class at COMMIT.
CREATE OR REPLACE FUNCTION baobab_native.fact_acct_commit_fence() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE source_table text; root_t text; root_r integer;
BEGIN
  IF NOT baobab_native.client_is_placed(NEW.ad_client_id::integer) THEN
    RETURN NULL;
  END IF;
  SELECT t.tablename INTO source_table FROM adempiere.ad_table t WHERE t.ad_table_id = NEW.ad_table_id;
  IF source_table IS NOT NULL THEN
    SELECT g.root_table, g.root_record INTO root_t, root_r
      FROM baobab_native.governed_root(source_table, NEW.record_id::integer) g;
  END IF;
  IF root_t IS NULL OR root_r IS NULL
     OR NOT baobab_native.has_governed_attribution(NEW.ad_client_id::integer, root_t, root_r) THEN
    RAISE EXCEPTION 'BAOBAB_NATIVE_FINANCE_DENIED: ledger posting without current authority at COMMIT'
      USING ERRCODE = '42501';
  END IF;
  RETURN NULL;
END $$;

-- Matching rows: inserting, changing or deleting one needs current authority
-- of its root document's own class in this transaction.
CREATE FUNCTION baobab_native.match_commit_fence() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE client integer; root_t text; root_r integer;
BEGIN
  IF TG_OP = 'DELETE' THEN client := OLD.ad_client_id::integer; ELSE client := NEW.ad_client_id::integer; END IF;
  IF NOT baobab_native.client_is_placed(client) THEN
    RETURN NULL;
  END IF;
  IF TG_OP = 'DELETE' THEN
    -- The row is gone: decide its root from the deleted values, by the same rule.
    IF TG_ARGV[0] = 'M_MatchPO' AND COALESCE((to_jsonb(OLD) ->> 'm_inoutline_id')::numeric, 0) > 0 THEN
      SELECT 'M_InOut', l.m_inout_id::integer INTO root_t, root_r FROM adempiere.m_inoutline l
       WHERE l.m_inoutline_id = (to_jsonb(OLD) ->> 'm_inoutline_id')::numeric;
    ELSIF COALESCE((to_jsonb(OLD) ->> 'c_invoiceline_id')::numeric, 0) > 0 THEN
      SELECT 'C_Invoice', l.c_invoice_id::integer INTO root_t, root_r FROM adempiere.c_invoiceline l
       WHERE l.c_invoiceline_id = (to_jsonb(OLD) ->> 'c_invoiceline_id')::numeric;
    END IF;
  ELSE
    SELECT g.root_table, g.root_record INTO root_t, root_r
      FROM baobab_native.governed_root(TG_ARGV[0], (to_jsonb(NEW) ->> TG_ARGV[1])::numeric::integer) g;
  END IF;
  IF root_t IS NULL OR root_r IS NULL OR NOT baobab_native.has_governed_attribution(client, root_t, root_r) THEN
    RAISE EXCEPTION 'BAOBAB_NATIVE_FINANCE_DENIED: matching without an authorised root at COMMIT'
      USING ERRCODE = '42501';
  END IF;
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER baobab_match_commit_fence AFTER INSERT OR UPDATE OR DELETE ON adempiere.m_matchpo
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
  EXECUTE FUNCTION baobab_native.match_commit_fence('M_MatchPO', 'm_matchpo_id');
CREATE CONSTRAINT TRIGGER baobab_match_commit_fence AFTER INSERT OR UPDATE OR DELETE ON adempiere.m_matchinv
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
  EXECUTE FUNCTION baobab_native.match_commit_fence('M_MatchInv', 'm_matchinv_id');

-- Payment selections drive remittance printing and bank-file export: a native
-- disbursement-instruction path that no class covers. Refused outright.
CREATE FUNCTION baobab_native.forbid_disbursement_instruction() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE client integer;
BEGIN
  IF TG_OP = 'DELETE' THEN client := OLD.ad_client_id::integer; ELSE client := NEW.ad_client_id::integer; END IF;
  IF baobab_native.client_is_placed(client) THEN
    RAISE EXCEPTION 'BAOBAB_NATIVE_FINANCE_DENIED: native disbursement instructions are not governed'
      USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['c_payselection', 'c_payselectionline', 'c_payselectioncheck'] LOOP
    EXECUTE format('CREATE TRIGGER baobab_forbid_disbursement_instruction BEFORE INSERT OR UPDATE OR DELETE
      ON adempiere.%I FOR EACH ROW EXECUTE FUNCTION baobab_native.forbid_disbursement_instruction()', t);
  END LOOP;
END $$;

-- The facts that decide a purchase-side class are fixed once the row exists,
-- like the direction (N0005): a vendor receipt cannot become a return, nor a
-- recorded outbound payment an online one.
CREATE TRIGGER baobab_class_lock_movementtype BEFORE UPDATE OF movementtype ON adempiere.m_inout
  FOR EACH ROW EXECUTE FUNCTION baobab_native.forbid_direction_change('movementtype');

CREATE FUNCTION baobab_native.forbid_outbound_online_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF baobab_native.client_is_placed(OLD.ad_client_id::integer) AND OLD.isreceipt = 'N'
     AND NEW.isonline IS DISTINCT FROM OLD.isonline THEN
    RAISE EXCEPTION 'BAOBAB_NATIVE_FINANCE_DENIED: a recorded vendor payment cannot become an online payment'
      USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER baobab_class_lock_isonline BEFORE UPDATE OF isonline ON adempiere.c_payment
  FOR EACH ROW EXECUTE FUNCTION baobab_native.forbid_outbound_online_change();
